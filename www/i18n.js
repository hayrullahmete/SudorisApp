let currentLanguage = 'tr';

function t(key, values = {}) {
    const template = translations[currentLanguage][key] ?? translations.tr[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

function applyTranslations() {
    document.documentElement.lang = currentLanguage;
    document.title = t('document.title');

    document.querySelectorAll('[data-i18n]').forEach(element => {
        element.textContent = t(element.dataset.i18n);
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
        element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    });

    document.querySelectorAll('[data-language-choice]').forEach(button => {
        button.setAttribute('aria-pressed', String(button.dataset.languageChoice === currentLanguage));
    });

    if (typeof refreshLocalizedGameUI === 'function') refreshLocalizedGameUI();
}

function setLanguage(language) {
    if (!Object.prototype.hasOwnProperty.call(translations, language) || language === currentLanguage) return;
    currentLanguage = language;
    localStorage.setItem('sudoris_language', currentLanguage);
    applyTranslations();
}

function initializeLanguage() {
    const savedLanguage = localStorage.getItem('sudoris_language');
    const browserPrefersEnglish = navigator.language?.toLowerCase().startsWith('en');
    currentLanguage = Object.prototype.hasOwnProperty.call(translations, savedLanguage)
        ? savedLanguage
        : browserPrefersEnglish ? 'en' : 'tr';
    applyTranslations();
}

initializeLanguage();
